/**
 * Автогенерация статей-справочников из текущего registry.
 * Каждый раз возвращает свежие данные — если в код добавили новое условие
 * или действие, оно появится в документации без правок этого файла.
 */
export function buildRefDocs() {
  return [
    {
      id: 'ref-conditions',
      title: 'Справочник условий',
      category: 'Справочник',
      content: buildRef('conditions'),
    },
    {
      id: 'ref-actions',
      title: 'Справочник действий',
      category: 'Справочник',
      content: buildRef('actions'),
    },
  ];
}

function buildRef(kind) {
  const map = kind === 'conditions' ? registry.conditions : registry.actions;
  const all = map.all();

  const byCat = new Map();
  for (const it of all) {
    const cat = it.category || 'Прочее';
    if (!byCat.has(cat)) byCat.set(cat, []);
    byCat.get(cat).push(it);
  }

  const kindRu = kind === 'conditions' ? 'Условия' : 'Действия';
  let md = `# Справочник: ${kindRu}\n\n`;
  md += `Всего элементов: **${all.length}**. Сгруппированы по категориям.\n\n`;

  for (const [cat, items] of byCat) {
    md += `## ${cat}\n\n`;
    for (const it of items) {
      md += `### ${it.label || it.id}\n\n`;

      if (it.description) {
        md += `${it.description}\n\n`;
      }

      md += `Идентификатор: \`${it.id}\`\n\n`;

      if (it.params && it.params.length) {
        md += 'Параметры:\n\n';
        for (const p of it.params) {
          md += `- **${p.label || p.id}**: тип \`${p.type}\`, id \`${p.id}\``;
          if (p.default !== undefined) {
            md += `, по умолчанию \`${JSON.stringify(p.default)}\``;
          }
          if (p.options && p.options.length) {
            md += `, варианты: ${p.options.map((o) => '`' + o + '`').join(', ')}`;
          }
          md += '\n';
        }
        md += '\n';
      } else {
        md += 'Без параметров.\n\n';
      }
    }
  }

  return md;
}